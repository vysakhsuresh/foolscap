/**
 * Downloads the site's font and self-hosts it.
 *
 * Nothing on a tool page may come from a third party, the CSP forbids it, and
 * a font that silently falls back turns the one typeface with personality into
 * the system default. So the file lives in the repo with its licence beside it.
 *
 *
 * Writes:
 *   app/public/fonts/*.woff2             the font files, one per subset
 *   app/src/ui/fonts.css                 @font-face rules, bundled with the app
 *   app/public/fonts/OFL-*.txt           the licence that came with the family
 *
 *   node scripts/fetch-fonts.mjs
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = resolve(ROOT, 'app/public/fonts');
const CSS_OUT = resolve(ROOT, 'app/src/ui/fonts.css');

// A modern UA, or the API answers with .ttf instead of .woff2.
const UA = 'Mozilla/5.0 (Linux; Android 11) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Mobile Safari/537.36';

// Only the subsets this site can show. Dropping vietnamese keeps the download small.
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

const FAMILIES = [
  // The one face for everything: the same as layerbit.co.in and the Sheaf app,
  // so the family reads as one. Variable weight 300..700 in one file per subset.
  { family: 'Space Grotesk', spec: 'Space+Grotesk:wght@300..700', slug: 'space-grotesk', ofl: 'spacegrotesk' },
];

async function get(url, as = 'text') {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
}

/** Pull the subset comment + descriptors out of each @font-face block. */
function parseCss(css) {
  const faces = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const [, subset, body] = m;
    const pick = (name) => (body.match(new RegExp(name + ':\\s*([^;]+);')) || [])[1]?.trim();
    const url = (body.match(/url\(([^)]+)\)/) || [])[1];
    if (!url) continue;
    faces.push({
      subset,
      family: (pick('font-family') || '').replace(/['"]/g, ''),
      weight: pick('font-weight') || '400',
      style: pick('font-style') || 'normal',
      unicodeRange: pick('unicode-range') || '',
      url,
    });
  }
  return faces;
}

async function main() {
  await mkdir(FONT_DIR, { recursive: true });
  const written = new Set();
  const cssOut = [
    '/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */',
    '/* Licence: app/public/fonts/OFL-*.txt */',
    '',
  ];
  let total = 0;

  for (const fam of FAMILIES) {
    const css = await get(`https://fonts.googleapis.com/css2?family=${fam.spec}&display=swap`);
    for (const face of parseCss(css)) {
      if (!KEEP_SUBSETS.has(face.subset)) continue;
      const italic = face.style === 'italic' ? '-italic' : '';
      const file = `${fam.slug}-${face.subset}${italic}.woff2`;
      const bytes = await get(face.url, 'buffer');
      await writeFile(resolve(FONT_DIR, file), bytes);
      written.add(file);
      total += bytes.length;
      cssOut.push(
        '@font-face {',
        `  font-family: '${face.family}';`,
        `  font-style: ${face.style};`,
        `  font-weight: ${face.weight};`,
        '  font-display: swap;',
        `  src: url('/fonts/${file}') format('woff2');`,
        `  unicode-range: ${face.unicodeRange};`,
        '}',
        '',
      );
      console.log(`  ${file.padEnd(44)} ${String(bytes.length).padStart(7)} bytes  (${face.family} ${face.weight})`);
    }
    try {
      const txt = await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${fam.ofl}/OFL.txt`);
      await writeFile(resolve(FONT_DIR, `OFL-${fam.slug}.txt`), txt);
    } catch (err) {
      console.warn(`  ! could not fetch the licence for ${fam.family}: ${err.message}`);
      console.warn(`    Add ofl/${fam.ofl}/OFL.txt from github.com/google/fonts by hand.`);
    }
  }

  await writeFile(CSS_OUT, cssOut.join('\n'));

  // A .woff2 in here that this run did not write is dead weight from an earlier run.
  for (const name of await readdir(FONT_DIR)) {
    if (name.endsWith('.woff2') && !written.has(name)) await rm(resolve(FONT_DIR, name));
  }
  console.log(`\n${written.size} font files, ${(total / 1024).toFixed(0)} KB in total -> app/public/fonts/`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
